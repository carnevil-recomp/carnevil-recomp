/*
 * fog.c - the level fog switch (0x800d6e60-0x800d6eec, a small file in front of lights.c):
 * on or off, and the Glide fog set-up the draw pass applies each frame.
 */
#include <glide/glide.h>

int	fog_enabled;				/* 0x801e6fe8 */

/* 0x80179da8: GR_FOG_TABLE_SIZE entries */
GrFog_t	fog_table[64] =
{
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x01, 0x02, 0x02, 0x04, 0x06, 0x08, 0x0b, 0x10,
	0x18, 0x1f, 0x2a, 0x3a, 0x55, 0x69, 0x83, 0xa5, 0xcd, 0xe0, 0xf1, 0xfb, 0xfe, 0xfe, 0xfe, 0xfe,
	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
};

/* 0x800d6e60, 0x800d6e70, 0x800d6e84 */
void reset_fog(void)
{
	fog_enabled = 0;
}

void enable_fog(void)
{
	fog_enabled = 1;
}

void disable_fog(void)
{
	fog_enabled = 0;
}

/* 0x800d6e94: once per frame */
void apply_fog(void)
{
	if(fog_enabled)
	{
		grFogMode(GR_FOG_WITH_TABLE);
		grFogColorValue(0xff222022);
		grFogTable(fog_table);
	}
	else
	{
		grFogMode(GR_FOG_DISABLE);
	}
}
