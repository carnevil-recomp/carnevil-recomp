#!/usr/bin/env python3
"""Extract the shared texmap tables (0x8017c2b0-0x8017d230 in GAME.EXE's .data: the weapon
sprites, the smoke, blood, fire, spark and explosion sets and the per-level sets) as C
initializers for src/game/texmaps_data.c. A texmap_t is 32 bytes: key, flags, param, index
(filled in at load) and a 16-byte file name."""
import os, struct

here = os.path.dirname(os.path.abspath(__file__)) + '/..'
exe = open(here + '/original/partition/GAME.EXE', 'rb').read()
BASE = 0x800c4000
HDR = 8

def rd(a, n): return exe[a - BASE + HDR:a - BASE + HDR + n]

TABLES = [
    ('main_weapon_texmap', 0x8017c2b0, 0x1d), ('blood_drops_texmap', 0x8017c650, 4),
    ('blood_drops_nv_texmap', 0x8017c6d0, 4), ('text_texmap', 0x8017c750, 1),
    ('smoketall_texmap', 0x8017c770, 1), ('gunsmoke_texmap', 0x8017c790, 5),
    ('explosion_texmap', 0x8017c830, 8), ('blood_texmap', 0x8017c930, 4),
    ('bloodnv_texmap', 0x8017c9b0, 4), ('smokesplat_texmap', 0x8017ca30, 4),
    ('fire_texmap', 0x8017cab0, 5), ('spark_texmap', 0x8017cb50, 5),
    ('hhouse_texmap', 0x8017cbf0, 4), ('hhouse_blood_texmap', 0x8017cc70, 2),
    ('hhouse_noblood_texmap', 0x8017ccb0, 2), ('freakshow_texmap', 0x8017ccf0, 3),
    ('freakshow_alt_texmap', 0x8017cd50, 3), ('freakshow_blood_texmap', 0x8017cdb0, 3),
    ('freakshow_noblood_texmap', 0x8017ce10, 3), ('rickity_texmap', 0x8017ce70, 1),
    ('rickity_blood_texmap', 0x8017ce90, 2), ('rickity_noblood_texmap', 0x8017ced0, 2),
    ('btop_texmap', 0x8017cf10, 0x13), ('blood_btop_texmap', 0x8017d170, 3),
    ('noblood_btop_texmap', 0x8017d1d0, 3),
]

out = ['/* texmaps_data.c - the shared texmap tables (0x8017c2b0-0x8017d230), generated by',
       '   tools/extract_texmaps.py: edit that, not this. See texmaps.c for who loads what. */',
       '#include "texmap.h"', '']
for name, base, n in TABLES:
    out.append('texmap_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
    for i in range(n):
        e = rd(base + i * 32, 32)
        key, flags, param, index = struct.unpack('<4i', e[:16])
        fname = e[16:].split(b'\0')[0].decode()
        out.append('\t{ 0x%x, %d, 0x%x, %d, "%s" },' % (key, flags, param & 0xffffffff, index, fname))
    out.append('};\n')
open(here + '/src/game/texmaps_data.c', 'w').write('\n'.join(out))
print('wrote src/game/texmaps_data.c')

# the Rickety Town objects' tables (0x80193ff0-0x80194230, the thrown food, presents and coal)
RICKITY = [('rickitytown_food_texmap', 0x80193ff0, 8), ('rickitytown_present_texmap', 0x80194170, 4),
           ('coal_texmap', 0x80194210, 1)]
out = ['/* rickity_objects_data.c - the Rickety Town objects\' texmap tables (0x80193ff0-0x80194230),',
       '   generated by tools/extract_texmaps.py: edit that, not this. */', '#include "texmap.h"', '']
for name, base, n in RICKITY:
    out.append('texmap_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
    for i in range(n):
        e = rd(base + i * 32, 32)
        key, flags, param, index = struct.unpack('<4i', e[:16])
        fname = e[16:].split(b'\0')[0].decode()
        out.append('\t{ 0x%x, %d, 0x%x, %d, "%s" },' % (key, flags, param & 0xffffffff, index, fname))
    out.append('};\n')
open(here + '/src/game/rickity_objects_data.c', 'w').write('\n'.join(out))
print('wrote src/game/rickity_objects_data.c')
