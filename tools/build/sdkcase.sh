#!/bin/sh
# The SDK's DOS-era headers are named in capitals (DIR.H, STDLIB.H, ...) and the sources include
# them in lower case, which only resolves on a case-insensitive file system (macOS, DOS). On a
# case-sensitive one (Linux) the Makefile adds this directory of lower-case links to them as a
# fallback include path. Names are compared exactly, from a listing, because a case-insensitive
# disk shared into a Linux VM answers "exists" for any spelling.
# With --wrap (the native port), each entry is a small header instead of a link: glibc's
# features.h defines _POSIX_SOURCE, and the DJGPP headers hide their DOS parts (struct ffblk,
# findfirst, ...) under it, so the wrapper lifts it around the SDK header and restores it.
# usage: tools/build/sdkcase.sh [--wrap] SDK_INCLUDE_DIR OUT_DIR
set -e
WRAP=0; [ "$1" = "--wrap" ] && { WRAP=1; shift; }
SRC="$(cd "$1" && pwd)"
mkdir -p "$2"; OUT="$(cd "$2" && pwd)"
find "$OUT" -mindepth 1 -delete
LIST="$OUT/.files"
(cd "$SRC" && find . -type f) > "$LIST"
while read -r f; do
	low="$(printf '%s' "$f" | tr 'A-Z' 'a-z')"
	[ "$low" = "$f" ] && continue
	grep -qxF "$low" "$LIST" && continue	# a real lower-case file of that name exists
	mkdir -p "$OUT/$(dirname "$low")"
	if [ $WRAP = 1 ]; then
		cat > "$OUT/$low" <<EOW
/* generated by tools/build/sdkcase.sh: the SDK's ${f#./} with glibc's _POSIX_SOURCE lifted */
#ifdef _POSIX_SOURCE
#define SDKCASE_POSIX_SOURCE
#undef _POSIX_SOURCE
#endif
#include "$SRC/${f#./}"
#ifdef SDKCASE_POSIX_SOURCE
#undef SDKCASE_POSIX_SOURCE
#define _POSIX_SOURCE 1
#endif
EOW
	else
		ln -sf "$SRC/$f" "$OUT/$low"
	fi
done < "$LIST"
rm -f "$LIST"
touch "$OUT/.stamp"
