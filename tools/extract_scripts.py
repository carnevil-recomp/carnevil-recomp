#!/usr/bin/env python3
"""Extract the movie scripts stored in GAME.EXE's text segment (0x80110b04-0x80114560) into
src/game/movie_scripts.c. Each script is a word stream read by do_script (script.c): the
opcode table below says how many operands each keyword takes and which are function
pointers, variable addresses or labels. Names come from config/names.txt, binja_symbols.txt
and functions_v103.txt. usage: extract_scripts.py [--stubs]  (--stubs lists the referenced
functions and variables so the port can define what it lacks)"""
import struct, sys, os, glob, re
here = os.path.dirname(os.path.abspath(__file__)) + '/..'
BASE = 0x800c4000
exe = None
for p in glob.glob(here + '/original/partition/*'):
    if p.lower().endswith('game.exe'): exe = open(p, 'rb').read()
if exe is None: sys.exit('original/partition/GAME.EXE missing')
def word(a): return struct.unpack('<i', exe[a - BASE + 8:a - BASE + 12])[0]

# keyword -> operand kinds: n number, f function, v variable, l label
OPS = {1: 'n', 3: 'n', 2: 'l', 5: 'f', 6: 'n', 19: 'nnn', 25: 'nn', 12: 'n', 14: 'n', 16: 'n',
       17: 'n', 21: 'n', 22: 'n', 23: 'n', 26: 'n', 29: 'n', 27: 'n', 28: 'n', 15: '', 18: '',
       13: 'n', 7: 'v', 8: 'v', 4: 'vl', 10: 'n', 24: 'n', 11: 'fl', 20: 'n', 9: ''}

# the scripts, in address order: (array name, start, [entry labels (name, addr)])
SCRIPTS = [
    ('hhouse_script', 0x80110b04, [('hhouse_script', 0x80110b04)]),
    ('freakshow_script', 0x80111928, [('freakshow_script', 0x80111928)]),
    ('rickity_town_script', 0x80112748, [('rickity_town_script', 0x80112748)]),
    ('movie_scripts', 0x801130b8, [('intro_script', 0x801130b8), ('attract2_script', 0x8011312c),
                                   ('end_script', 0x80113180),
                                   ('end_script_loop', 0x801131c4), ('midway_script', 0x801131e0),
                                   ('attract_script', 0x801131ec), ('attract3_script', 0x801131f8),
                                   ('gallery_script', 0x80113204)]),
    ('bigtop_script', 0x80113218, [('bigtop_script', 0x80113218)]),
]
END = 0x80114560

names = {}
for line in open(here + '/config/functions_v103.txt'):
    f = line.split()
    if len(f) >= 3 and f[0].startswith('0x'): names[int(f[0], 16)] = f[2]
for line in open(here + '/config/binja_symbols.txt'):
    f = line.rstrip('\n').split('\t')
    if len(f) >= 3 and f[0].startswith('0x'): names[int(f[0], 16)] = f[2]
for line in open(here + '/config/names.txt'):
    f = line.split()
    if len(f) >= 2 and f[0].startswith('0x'): names[int(f[0], 16)] = f[1]
def fname(a): return names.get(a, 'func_%08x' % a)
def vname(a): return names.get(a, 'D_%08x' % a)

# first pass: decode every script into (addr, kind, value) entries
decoded = []     # per script: list of (addr, kind, value)
for i, (arr, start, entries) in enumerate(SCRIPTS):
    end = SCRIPTS[i + 1][1] if i + 1 < len(SCRIPTS) else END
    a = start; out = []
    while a < end:
        k = word(a)
        if k not in OPS:
            sys.exit('%s: unknown keyword %d at 0x%08x' % (arr, k, a))
        out.append((a, 'k', k)); a += 4
        for kind in OPS[k]:
            out.append((a, kind, word(a))); a += 4
    decoded.append(out)

def label_ref(target):
    for (arr, start, entries), out in zip(SCRIPTS, decoded):
        for j, (a, kind, v) in enumerate(out):
            if a == target:
                if arr == 'movie_scripts': return 'SCRIPT_LABEL(%d)' % j
                return '(script_word_t)&%s[%d]' % (arr, j)
    sys.exit('label 0x%08x is not the start of a word' % target)

fns, vars_ = {}, set()
lines = ['/* movie_scripts.c - the movie scripts stored in GAME.EXE\'s text segment',
         '   (0x80110b04-0x80114560), one array per script in address order. Generated by',
         '   tools/extract_scripts.py: edit that, not this. Keywords are the opcodes of',
         '   do_script (script.c); SCRIPT_FN/SCRIPT_VAR/SCRIPT_LABEL mark function pointers,',
         '   variables and jump targets. midway/attract/attract3/gallery are entry points into',
         '   movie_scripts[] (see movie.h). */',
         '#include "movie.h"', '']
body = []
for (arr, start, entries), out in zip(SCRIPTS, decoded):
    body.append('script_word_t\t%s[] =\n{' % arr)
    for j, (a, kind, v) in enumerate(out):
        for name, ea in entries:
            if ea == a: body.append('\t/* %s (0x%08x) */' % (name, a))
        if kind == 'k' or kind == 'n': body.append('\t%d,' % v)
        elif kind == 'f':
            n = fname(v & 0xffffffff)
            fns[n] = 'int' if (out[j - 1][2] == 11 or fns.get(n) == 'int') else 'void'   # opcode 11 tests the result
            body.append('\tSCRIPT_FN(%s),' % n)
        elif kind == 'v': vars_.add(vname(v & 0xffffffff)); body.append('\tSCRIPT_VAR(&%s),' % vname(v & 0xffffffff))
        elif kind == 'l': body.append('\t%s,' % label_ref(v & 0xffffffff))
    body.append('};\n')
for f in sorted(fns): lines.append('extern %s\t%s();' % (fns[f], f))
for v in sorted(vars_): lines.append('extern int\t%s;' % v)
lines.append('')
open(here + '/src/game/movie_scripts.c', 'w').write('\n'.join(lines + body))
# the entry offsets for movie.h
for (arr, start, entries), out in zip(SCRIPTS, decoded):
    if arr == 'movie_scripts':
        for name, ea in entries:
            j = [k for k, (a, kind, v) in enumerate(out) if a == ea][0]
            print('#define %s_OFFSET\t%d' % (name.upper().replace('_SCRIPT', '_SCRIPT'), j), file=sys.stderr)
if '--stubs' in sys.argv:
    print('FUNCTIONS', ' '.join('%s:%s' % (f, fns[f]) for f in sorted(fns)))
    print('VARIABLES', ' '.join(sorted(vars_)))
