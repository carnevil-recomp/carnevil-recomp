#!/usr/bin/env python3
"""Extract the six level light tables (0x80179e28-0x8017c1d0 in GAME.EXE's .data) as C
initializers for src/game/lights_data.c. Each entry is 56 bytes: start frame, end frame,
type, flags, three floats (a position in tenths or two angles), a colour, the falloff,
an unused float, an unused word and the camera light's life (see lights.c)."""
import os, struct, sys

here = os.path.dirname(os.path.abspath(__file__)) + '/..'
exe = open(here + '/original/partition/GAME.EXE', 'rb').read()
BASE = 0x800c4000
HDR = 8

def rd(a, n): return exe[a - BASE + HDR:a - BASE + HDR + n]

TABLES = [('hiscore_light_info', 0x80179e28, 6), ('hhouse_light_info', 0x80179f78, 0x44),
          ('freakshow_light_info', 0x8017ae58, 0x30), ('rickitytown_light_info', 0x8017b8d8, 0x24),
          ('bigtop_light_info', 0x8017c0b8, 3), ('attract_light_info', 0x8017c160, 2)]

def fl(x):
    s = repr(float('%.9g' % x))
    if '.' not in s and 'e' not in s: s += '.0'
    return s + 'f'

out = ['/* lights_data.c - the level light tables (0x80179e28-0x8017c1d0), generated by',
       '   tools/extract_lights.py: edit that, not this. See lights.c for the fields. */',
       '#include "lights.h"', '']
for name, base, n in TABLES:
    out.append('light_info_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
    for i in range(n):
        e = rd(base + i * 56, 56)
        w = struct.unpack('<14I', e); f = struct.unpack('<14f', e)
        out.append('\t{ %d, %d, %d, 0x%x, { %s, %s, %s }, { %s, %s, %s }, %s, %s, %d, %d },'
                   % (w[0], w[1], w[2], w[3], fl(f[4]), fl(f[5]), fl(f[6]), fl(f[7]), fl(f[8]), fl(f[9]), fl(f[10]), fl(f[11]), w[12], w[13]))
    out.append('};\n')
open(here + '/src/game/lights_data.c', 'w').write('\n'.join(out))
print('wrote src/game/lights_data.c')
