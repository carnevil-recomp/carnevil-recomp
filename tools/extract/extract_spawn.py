#!/usr/bin/env python3
"""Extract the four levels' spawn tables from GAME.EXE into src/game/enemies/spawn_data.c
(spawn_t, 0x2c bytes an entry: see spawn.h). The counts are load_level_spawn's."""
import struct, glob, os, sys
here = os.path.dirname(os.path.abspath(__file__)) + '/../..'
BASE = 0x800c4000
exe = None
for p in glob.glob(here + '/original/partition/*'):
    if p.lower().endswith('game.exe'): exe = open(p, 'rb').read()
if exe is None: sys.exit('original/partition/GAME.EXE missing')
TABLES = [('hhouse_spawn_blob', 0x80186628, 0xd1), ('freakshow_spawn_blob', 0x80188a14, 0xbd),
          ('rickity_spawn_blob', 0x8018aa90, 0x87), ('bigtop_spawn_blob', 0x8018c1c4, 0x96)]
def f(x):
    s = '%.9g' % x
    if 'e' not in s and '.' not in s: s += '.0'
    return s + 'f'
out = ['/* spawn_data.c - the levels\' spawn tables (0x80186628-0x8018db98 in GAME.EXE, .data),',
       '   generated by tools/extract/extract_spawn.py: edit that, not this. Fields: count, frame, die frame,',
       '   min_lock, thr1, thr2, type, state, unk10, unk12, x, y, z, ry, unk24, path, unk2a (spawn.h). */',
       '#include "spawn.h"', '']
for name, addr, n in TABLES:
    out.append('spawn_t\t%s[%d] =\n{' % (name, n))
    for i in range(n):
        o = addr - BASE + 8 + i * 0x2c
        (count, frame, die, lock, t1, t2, typ, state, u10, u12, x, y, z, ry, u24, path, u2a) = struct.unpack('<hhhhhhHHhhfffffhh', exe[o:o + 0x2c])
        out.append('\t{ %d, %d, %d, %d, %d, %d, 0x%04x, 0x%04x, %d, %d, %s, %s, %s, %s, %s, %d, %d },' % (count, frame, die, lock, t1, t2, typ, state, u10, u12, f(x), f(y), f(z), f(ry), f(u24), path, u2a))
    out.append('};\n')
open(here + '/src/game/enemies/spawn_data.c', 'w').write('\n'.join(out))
if '--types' in sys.argv:
    for name, addr, n in TABLES:
        types = {}
        for i in range(n):
            o = addr - BASE + 8 + i * 0x2c
            typ, = struct.unpack('<H', exe[o + 0xc:o + 0xe]); frame, = struct.unpack('<h', exe[o + 2:o + 4])
            types.setdefault(typ, []).append(frame)
        print(name, ' '.join('%04x:%d@%d' % (t, len(v), min(v)) for t, v in sorted(types.items())))
