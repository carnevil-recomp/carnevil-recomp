#!/usr/bin/env python3
"""Extract CarnEvil's coin pricing tables from GAME.EXE into src/game/core/pricing_data.c.

The credits code (0x800c75b0) picks an 88-byte pricing record from a continent table
(0x80179b40: 7 pointers to per-continent arrays of country pointers), each country pointing at
an array of records indexed by the "price" adjustment, or from a 32-entry table indexed by the
pricing dip switches (0x80179b60). Record layout: 13 words copied to credit_info_struct_2
(slot units, credits per coin, bonus thresholds...), 5 words of coin-counter setup, the
currency index (+0x48), the attract text (+0x4c), the name (+0x50) and one more pointer."""
import struct, sys, re
img = open('original/partition/GAME.EXE', 'rb').read()[8:]
LOAD = 0x800c4000
def w(a): return struct.unpack('<I', img[a - LOAD:a - LOAD + 4])[0]
def cstr(a):
    if not (0x800c4000 <= a < 0x801a0000): return None
    s = img[a - LOAD:a - LOAD + 200].split(b'\0')[0]
    try: t = s.decode('ascii')
    except UnicodeDecodeError: return None
    return t if all(32 <= ord(c) < 127 or c == '\n' for c in t) else None
def cq(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
RECSZ = 88
cont = [w(0x80179b40 + 4 * i) for i in range(7)]
bounds = sorted(set(c for c in cont if c)) + [0x80179b40]
countries = {}				# continent -> list of country record-array addresses
for i, c in enumerate(cont):
    if not c: countries[i] = []; continue
    end = min(b for b in bounds if b > c)
    countries[i] = [w(a) for a in range(c, end, 4)]
dip = [w(0x80179b60 + 4 * i) for i in range(32)]
# records: from every array start, step 88 while the name/text pointers are strings
starts = set(dip)
for lst in countries.values(): starts.update(lst)
recs = {}
for s in sorted(starts):
    a = s
    while (a == s or (cstr(w(a + 0x50)) and cstr(w(a + 0x4c)))) and a not in recs:
        recs[a] = True
        a += RECSZ
recs = sorted(recs)
idx = {a: i for i, a in enumerate(recs)}
out = ['/* pricing_data.c - generated by tools/extract/gen_pricing.py from GAME.EXE v1.0.3: do not edit */', '#include "credits.h"', '']
out.append('pricing_record_t pricing_records[%d] =\n{' % len(recs))
for a in recs:
    f = [w(a + 4 * k) for k in range(22)]
    extra = cstr(f[21])
    def sq(p):
        t = cstr(p)
        return cq(t) if t is not None else '0'
    out.append('\t/* %d: 0x%08x */ { %s, %d, %s, %s, %s },' % (idx[a], a, ', '.join(str(x) for x in f[:18]), f[18], sq(f[19]), sq(f[20]), sq(f[21])))
out.append('};\n')
for i in range(7):
    if countries[i]:
        out.append('static pricing_record_t *continent%d[%d] = { %s };' % (i, len(countries[i]), ', '.join('&pricing_records[%d]' % idx[p] for p in countries[i])))
out.append('\n/* 0x80179b40: per continent, a list of countries; each country is an array of records indexed by the price adjustment */')
out.append('pricing_record_t **pricing_continents[7] = { %s };' % ', '.join(('continent%d' % i) if countries[i] else '0' for i in range(7)))
out.append('\n/* 0x80179b60: the record each setting of the pricing dip switches selects */')
out.append('pricing_record_t *pricing_by_dip[32] =\n{')
for i in range(0, 32, 4): out.append('\t' + ', '.join('&pricing_records[%d]' % idx[dip[k]] for k in range(i, i + 4)) + ',')
out.append('};\n')
cur = [cstr(w(0x80177be8 + 4 * i)) for i in range(12)]
out.append('/* 0x80177be8 */\nchar *currency_names[12] = { %s };' % ', '.join(cq(c) for c in cur))
open('src/game/core/pricing_data.c', 'w').write('\n'.join(out) + '\n')
print(len(recs), 'records;', {i: len(v) for i, v in countries.items()})
