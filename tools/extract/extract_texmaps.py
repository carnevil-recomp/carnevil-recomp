#!/usr/bin/env python3
"""Extract the shared texmap tables (0x8017c2b0-0x8017d230 in GAME.EXE's .data: the weapon
sprites, the smoke, blood, fire, spark and explosion sets and the per-level sets) as C
initializers for src/game/render/texmaps_data.c. A texmap_t is 32 bytes: key, flags, param, index
(filled in at load) and a 16-byte file name."""
import os, struct

here = os.path.dirname(os.path.abspath(__file__)) + '/../..'
exe = open(here + '/original/partition/GAME.EXE', 'rb').read()
BASE = 0x800c4000
HDR = 8

def rd(a, n): return exe[a - BASE + HDR:a - BASE + HDR + n]

TABLES = [
    ('main_weapon_texmap', 0x8017c2b0, 0x1d), ('blood_drops_texmap', 0x8017c650, 4),
    ('blood_drops_nv_texmap', 0x8017c6d0, 4), ('text_texmap', 0x8017c750, 1),
    ('smoketall_texmap', 0x8017c770, 1), ('gunsmoke_texmap', 0x8017c790, 5),
    ('explosion_texmap', 0x8017c830, 8), ('blood_texmap', 0x8017c930, 4),
    ('bloodnv_texmap', 0x8017c9b0, 4), ('smokesplat_texmap', 0x8017ca30, 4),
    ('fire_texmap', 0x8017cab0, 5), ('spark_texmap', 0x8017cb50, 5),
    ('hhouse_texmap', 0x8017cbf0, 4), ('hhouse_blood_texmap', 0x8017cc70, 2),
    ('hhouse_noblood_texmap', 0x8017ccb0, 2), ('freakshow_texmap', 0x8017ccf0, 3),
    ('freakshow_alt_texmap', 0x8017cd50, 3), ('freakshow_blood_texmap', 0x8017cdb0, 3),
    ('freakshow_noblood_texmap', 0x8017ce10, 3), ('rickity_texmap', 0x8017ce70, 1),
    ('rickity_blood_texmap', 0x8017ce90, 2), ('rickity_noblood_texmap', 0x8017ced0, 2),
    ('btop_texmap', 0x8017cf10, 0x13), ('blood_btop_texmap', 0x8017d170, 3),
    ('noblood_btop_texmap', 0x8017d1d0, 3),
]

out = ['/* texmaps_data.c - the shared texmap tables (0x8017c2b0-0x8017d230), generated by',
       '   tools/extract/extract_texmaps.py: edit that, not this. See texmaps.c for who loads what. */',
       '#include "texmap.h"', '']
for name, base, n in TABLES:
    out.append('texmap_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
    for i in range(n):
        e = rd(base + i * 32, 32)
        key, flags, param, index = struct.unpack('<4i', e[:16])
        fname = e[16:].split(b'\0')[0].decode()
        out.append('\t{ 0x%x, %d, 0x%x, %d, "%s" },' % (key, flags, param & 0xffffffff, index, fname))
    out.append('};\n')
open(here + '/src/game/render/texmaps_data.c', 'w').write('\n'.join(out))
print('wrote src/game/render/texmaps_data.c')

# the enemies' weapons (weapons.c): one .data run of texmap tables and submesh tables, in
# address order, 0x80193ad0-0x80194650
WEAPONS = [
    ('texmap', 'hhouse_enemy_bone_texmap', 0x80193ad0, 1), ('submesh', 'bone_submesh', 0x80193af0, 1),
    ('texmap', 'hhouse_enemy_knife_texmap', 0x80193b10, 2), ('submesh', 'knife_submesh', 0x80193b50, 1),
    ('texmap', 'hhouse_enemy_hat_texmap', 0x80193b70, 1), ('submesh', 'hat_submesh', 0x80193b90, 1),
    ('texmap', 'wigs_texmap', 0x80193bb0, 10), ('submesh', 'wig_submesh', 0x80193cf0, 5),
    ('texmap', 'freakshow_enemy_sword_texmap', 0x80193d90, 2), ('submesh', 'sword_submesh', 0x80193dd0, 1),
    ('texmap', 'freakshow_enemy_club_texmap', 0x80193df0, 2), ('submesh', 'bat_submesh', 0x80193e30, 1),
    ('texmap', 'freakshow_enemy_hook_texmap', 0x80193e50, 2), ('submesh', 'hook_submesh', 0x80193e90, 1),
    ('texmap', 'freakshow_enemy_blade_texmap', 0x80193eb0, 2), ('submesh', 'blade_submesh', 0x80193ef0, 1),
    ('texmap', 'freakshow_enemy_pin_texmap', 0x80193f10, 2), ('submesh', 'pin_submesh', 0x80193f50, 1),
    ('texmap', 'freakshow_enemy_rattle', 0x80193f70, 3), ('submesh', 'rattle_submesh', 0x80193fd0, 1),
    ('texmap', 'rickitytown_food_texmap', 0x80193ff0, 8), ('submesh', 'food_submesh', 0x801940f0, 4),
    ('texmap', 'rickitytown_present_texmap', 0x80194170, 4), ('submesh', 'present_submesh', 0x801941f0, 1),
    ('texmap', 'coal_texmap', 0x80194210, 1), ('submesh', 'coal_submesh', 0x80194230, 1),
    ('texmap', 'btop_bone_texmap', 0x80194250, 3), ('submesh', 'btop_bone_submesh', 0x801942b0, 2),
    ('texmap', 'missile_texmap', 0x801942f0, 20), ('submesh', 'missile_submesh', 0x80194570, 7),
]
def ff(x):
    s = '%.9g' % x
    if 'e' not in s and '.' not in s: s += '.0'
    return s + 'f'
out = ['/* weapons_data.c - the enemies\' weapon tables (0x80193ad0-0x80194650: each weapon\'s texmaps',
       '   followed by its submesh table), generated by tools/extract/extract_texmaps.py: edit that, not this.',
       '   weapons.c loads and draws them. */', '#include "texmap.h"', '#include "model.h"', '']
for kind, name, base, n in WEAPONS:
    if kind == 'texmap':
        out.append('texmap_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
        for i in range(n):
            e = rd(base + i * 32, 32)
            key, flags, param, index = struct.unpack('<4i', e[:16])
            fname = e[16:].split(b'\0')[0].decode()
            out.append('\t{ 0x%x, %d, 0x%x, %d, "%s" },' % (key, flags, param & 0xffffffff, index, fname))
    else:
        out.append('submesh_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
        for i in range(n):
            fs, fe, anim, vs, ve, ns, ne, r, px, py, pz = struct.unpack('<hhIhhhhffff', rd(base + i * 32, 32))
            out.append('\t{ %d, %d, 0, %d, %d, %d, %d, %s, { %s, %s, %s } },' % (fs, fe, vs, ve, ns, ne, ff(r), ff(px), ff(py), ff(pz)))
    out.append('};\n')
open(here + '/src/game/enemies/weapons_data.c', 'w').write('\n'.join(out))
print('wrote src/game/enemies/weapons_data.c')

# the level-select gallery's tables (select.c): texmaps, submesh tables and the two aim light
# colours, 0x801917e0-0x80191d78
SELECT = [
    ('texmap', 'select_hhouse_texmap', 0x801917e0, 3), ('submesh', 'hhouse_select_submesh', 0x80191840, 3),
    ('texmap', 'select_freakshow_texmap', 0x801918a0, 4), ('submesh', 'freakshow_select_submesh', 0x80191920, 4),
    ('texmap', 'select_rickity_texmap', 0x801919a0, 14), ('submesh', 'rickity_select_submesh', 0x80191b60, 11),
    ('texmap', 'select_bigtop_texmap', 0x80191cc0, 1), ('submesh', 'bigtop_select_submesh', 0x80191ce0, 1),
    ('texmap', 'select_tick_texmap', 0x80191d00, 3), ('floats', 'select_light_colour[2][3]', 0x80191d60, 6),
]
out = ['/* select_data.c - the level-select gallery\'s tables (0x801917e0-0x80191d78), generated by',
       '   tools/extract/extract_texmaps.py: edit that, not this. select.c loads and draws them. */',
       '#include "texmap.h"', '#include "model.h"', '']
for kind, name, base, n in SELECT:
    if kind == 'texmap':
        out.append('texmap_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
        for i in range(n):
            e = rd(base + i * 32, 32)
            key, flags, param, index = struct.unpack('<4i', e[:16])
            fname = e[16:].split(b'\0')[0].decode()
            out.append('\t{ 0x%x, %d, 0x%x, %d, "%s" },' % (key, flags, param & 0xffffffff, index, fname))
    elif kind == 'submesh':
        out.append('submesh_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
        for i in range(n):
            fs, fe, anim, vs, ve, ns, ne, r, px, py, pz = struct.unpack('<hhIhhhhffff', rd(base + i * 32, 32))
            out.append('\t{ %d, %d, 0, %d, %d, %d, %d, %s, { %s, %s, %s } },' % (fs, fe, vs, ve, ns, ne, ff(r), ff(px), ff(py), ff(pz)))
    else:
        vals = struct.unpack('<%df' % n, rd(base, 4 * n))
        rows = [vals[i:i + 3] for i in range(0, n, 3)]
        out.append('float\t\t%s =\t\t/* 0x%08x */\n{' % (name, base))
        for r in rows:
            out.append('\t{ %s },' % ', '.join(ff(x) for x in r))
    out.append('};\n')
open(here + '/src/game/core/select_data.c', 'w').write('\n'.join(out))
print('wrote src/game/core/select_data.c')

# the jester's tables (jester.c): texmaps, submesh table, the lights' colours and angles, the
# cue tables, 0x801929c0-0x80192ff0
JESTER = [
    ('texmap', 'jester_texmap', 0x801929c0, 30), ('submesh', 'jester_submesh', 0x80192d80, 14),
    ('floats', 'jester_light_colour[3][3]', 0x80192f40, 9), ('floats', 'jester_light_angles[3]', 0x80192f64, 3),
    ('int', 'jester_light_flips', 0x80192f70, 1), ('ints', 'jester_dance_cues[15]', 0x80192f74, 15),
    ('int', 'jester_dance_cue', 0x80192fb0, 1), ('ints', 'jester_hit_cues[14]', 0x80192fb4, 14),
    ('int', 'jester_hit_cue', 0x80192fec, 1),
]
out = ['/* jester_data.c - the jester\'s tables (0x801929c0-0x80192ff0), generated by',
       '   tools/extract/extract_texmaps.py: edit that, not this. jester.c loads and uses them. */',
       '#include "texmap.h"', '#include "model.h"', '']
for kind, name, base, n in JESTER:
    if kind == 'texmap':
        out.append('texmap_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
        for i in range(n):
            e = rd(base + i * 32, 32)
            key, flags, param, index = struct.unpack('<4i', e[:16])
            fname = e[16:].split(b'\0')[0].decode()
            out.append('\t{ 0x%x, %d, 0x%x, %d, "%s" },' % (key, flags, param & 0xffffffff, index, fname))
        out.append('};\n')
    elif kind == 'submesh':
        out.append('submesh_t\t%s[%d] =\t\t/* 0x%08x */\n{' % (name, n, base))
        for i in range(n):
            fs, fe, anim, vs, ve, ns, ne, r, px, py, pz = struct.unpack('<hhIhhhhffff', rd(base + i * 32, 32))
            out.append('\t{ %d, %d, 0, %d, %d, %d, %d, %s, { %s, %s, %s } },' % (fs, fe, vs, ve, ns, ne, ff(r), ff(px), ff(py), ff(pz)))
        out.append('};\n')
    elif kind == 'floats':
        vals = struct.unpack('<%df' % n, rd(base, 4 * n))
        if '][' in name:
            rows = [vals[i:i + 3] for i in range(0, n, 3)]
            out.append('float\t\t%s =\t\t/* 0x%08x */\n{' % (name, base))
            for r in rows:
                out.append('\t{ %s },' % ', '.join(ff(x) for x in r))
            out.append('};\n')
        else:
            out.append('float\t\t%s = { %s };\t\t/* 0x%08x */\n' % (name, ', '.join(ff(x) for x in vals), base))
    elif kind == 'ints':
        vals = struct.unpack('<%di' % n, rd(base, 4 * n))
        out.append('int\t\t%s = { %s };\t\t/* 0x%08x */\n' % (name, ', '.join(str(x) for x in vals), base))
    else:
        out.append('int\t\t%s = %d;\t\t/* 0x%08x */\n' % (name, struct.unpack('<i', rd(base, 4))[0], base))
open(here + '/src/game/enemies/jester_data.c', 'w').write('\n'.join(out))
print('wrote src/game/enemies/jester_data.c')
